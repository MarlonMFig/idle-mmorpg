import type { ItemDefinition, ItemRarity } from '@/types/loot';

const STACK_BY_RARITY: Record<ItemRarity, number> = {
  common: 99,
  uncommon: 99,
  rare: 50,
  epic: 30,
  legendary: 20,
  mythic: 10,
};

function item(id: string, name: string, rarity: ItemRarity, iconFile?: string): ItemDefinition {
  return {
    id,
    name,
    rarity,
    stackMax: STACK_BY_RARITY[rarity],
    ...(iconFile ? { iconSrc: `/ui/items/naruto/${iconFile}` } : undefined),
  };
}

